// 실제 로컬 중계 서버와 서로 다른 임시 저장 공간의 두 게임으로 동기화를 확인한다.
const { app, BrowserWindow } = require('electron');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
app.setPath('userData',fs.mkdtempSync(path.join(os.tmpdir(),'factory-multiplayer-')));
const delay=ms=>new Promise(r=>setTimeout(r,ms));
app.whenReady().then(async()=>{
  const {createServer}=await import('vite');
  const server=await createServer({server:{host:'127.0.0.1',port:0}});
  const make=partition=>new BrowserWindow({show:false,width:1280,height:800,webPreferences:{partition,offscreen:true,backgroundThrottling:false}});
  const host=make('host'),guest=make('guest');
  const js=(win,code)=>win.webContents.executeJavaScript(`(async()=>{${code}})()`);
  let checks=0;
  const check=async(name,win,code)=>{if(!await js(win,code))throw Error(name);checks++;console.log(`PASS ${name}`);};
  const until=async(win,code,label)=>{const start=Date.now();while(Date.now()-start<6000){await js(host,'session.advance(0);');await js(guest,'session.advance(0);');if(await js(win,`return ${code};`))return;await delay(35);}throw Error(`timeout: ${label}`);};
  try{
    await server.listen();const url=server.resolvedUrls.local[0];
    await host.loadURL(url);await guest.loadURL(url);
    for(const win of [host,guest])await js(win,`window.requestAnimationFrame=()=>0;game.setSpeed(0);document.querySelectorAll('.modal').forEach(e=>e.hidden=true);`);
    await until(host,'session.connected','host connection');await until(guest,'session.connected','guest connection');
    await js(guest,`game.save();window.ownSeed=game.getWorld().seed;window.ownSave=localStorage.getItem('automation-game/save-v1');`);
    await js(host,`const {World}=await import('/src/sim/world.ts');const w=new World(40,30);w.rules='regional-v1';w.seed=987654;w.forestsLoaded=true;w.createHub(0,0);w.setResource(39,29,'water',Infinity);
      for(const t of w.techs)w.applyTech(t.id);for(const item of (await import('/src/data/items.ts')).ITEM_IDS)w.stock.set(item,10000);
      const error=game.importSave(JSON.stringify(w.serialize()));if(error)throw Error(error);session.createRoom();`);
    await until(host,`session.role==='host'`,'room creation');await until(guest,'session.roomOpen','room discovery');
    await js(guest,'session.joinRoom();');
    await until(guest,`session.role==='guest'&&session.synced&&game.getWorld().seed===987654`,'join snapshot');
    const hash=await js(host,'return game.getWorld().checksum();');
    await check('real host and guest start from the same snapshot',guest,`return game.getWorld().checksum()===${hash};`);
    await check('guest cannot overwrite the personal save',guest,`return game.save()===false&&localStorage.getItem('automation-game/save-v1')===ownSave;`);
    const player=await js(guest,'return session.me;');
    await js(guest,`camera.x=20.5;camera.y=20.5;camera.zoom=24;const c=document.getElementById('game');c.setPointerCapture=()=>{};
      window.fire=(type,x,y)=>{const [clientX,clientY]=camera.worldToScreen(x,y);const e=new PointerEvent(type,{pointerId:1,button:0,buttons:1,clientX,clientY,bubbles:true});(type==='pointerup'?window:c).dispatchEvent(e);};
      game.input.setTool('road');fire('pointerdown',20.5,20.5);fire('pointermove',22.5,20.5);`);
    await until(host,`!!game.getWorld().buildingAt(22,20)`,'guest drag reaches host');
    await js(host,`session.sendSnapshot(${player});`);
    await until(guest,`game.input.tool===null`,'snapshot cancels old drag');
    await until(host,`game.getWorld().nextEdit(false,${player})?.length===3`,'snapshot finalizes the guest edit');
    await check('resync closes the current guest edit on the host',host,`return game.getWorld().nextEdit(false,${player}).length===3;`);
    await js(guest,`game.input.setTool('road');fire('pointerdown',25.5,20.5);fire('pointerup',25.5,20.5);`);
    await until(host,`!!game.getWorld().buildingAt(25,20)`,'next guest edit');
    await js(guest,'game.input.undoRedo(false);');
    await until(host,`!game.getWorld().buildingAt(25,20)`,'guest undo');
    await check('the next guest drag can be undone independently after resync',host,`return !!game.getWorld().buildingAt(20,20)&&!!game.getWorld().buildingAt(22,20);`);
    await js(guest,'game.input.undoRedo(false);');
    await until(host,`!game.getWorld().buildingAt(20,20)`,'undo original drag');
    const after=await js(host,'return game.getWorld().checksum();');
    await until(guest,`game.getWorld().checksum()===${after}`,'final matching worlds');
    await check('host and guest agree after two undos',guest,`return game.getWorld().checksum()===${after};`);
    const trip=await js(host,`const w=game.getWorld();for(let x=8;x<=33;x++)w.place('road',x,12,0);
      window.tripA=w.place('station',10,10,0);window.tripB=w.place('station',24,10,0);window.tripC=w.place('station',31,10,0);
      w.setStationMode(tripB,'unload');w.setStationMode(tripC,'unload');tripA.inBuf.set('motor',40);
      window.tripTruck=w.buildTruck(tripA);w.setStops(tripTruck,[{id:tripA.id,act:'load'},{id:tripB.id,act:'unload'}]);w.setPlan(tripTruck,[{item:'motor',cap:20}],0,false);
      game.speed=1;for(let i=0;i<600&&tripTruck.stop!==1;i++)session.advance(1/60);game.speed=0;session.worldReplaced();
      return {vehicle:tripTruck.id,a:tripA.id,b:tripB.id,c:tripC.id};`);
    await until(guest,`game.getWorld().vehicles.has(${trip.vehicle})`,'shipment snapshot');
    await js(guest,`game.exec({t:'route',id:${trip.vehicle},stops:[{id:${trip.a},act:'load'},{id:${trip.c},act:'unload'}]});`);
    await until(host,'tripTruck.pendingStops!==null','guest route change');
    await js(host,`session.sendSnapshot(${player});`);
    await until(guest,`game.getWorld().vehicles.get(${trip.vehicle})?.pendingStops?.[1].id===${trip.c}`,'pending route snapshot');
    await check('guest route edit preserves the active delivery across a real resync',guest,`const v=game.getWorld().vehicles.get(${trip.vehicle});return v.stops[1].id===${trip.b}&&v.route[1].id===${trip.c}&&v.load===20;`);
    await js(host,`game.speed=1;for(let i=0;i<40;i++)session.advance(1);game.speed=0;session.advance(0);`);
    const deliveredHash=await js(host,'return game.getWorld().checksum();');
    await until(guest,`game.getWorld().checksum()===${deliveredHash}`,'shipment lockstep');
    await check('old and new destinations each receive the correct shipment',host,`const w=game.getWorld();return w.poolCount(tripB,'motor')===20&&w.poolCount(tripC,'motor')===20&&tripTruck.pendingStops===null;`);
    await check('host and guest still agree after deferred route delivery',guest,`return game.getWorld().checksum()===${deliveredHash};`);
    await js(guest,`game.input.paste={w:1,h:1,entries:[]};game.input.selectedVehicle=1;game.input.multi=[1,2];`);
    await js(host,`game.newGame();`);
    await until(guest,`game.getWorld().width===256&&game.input.paste===null`,'host starts a new world');
    await check('host new game clears stale selections and blueprint on the guest',guest,`return game.input.selectedVehicle===null&&!game.input.multi.length&&localStorage.getItem('automation-game/save-v1')===ownSave;`);
    await js(guest,'session.leaveRoom();');
    await until(guest,`session.role==='solo'&&!session.borrowed`,'leave room');
    await check('leaving the room restores the personal factory',guest,`return game.getWorld().seed===ownSeed&&game.input.paste===null;`);
    console.log(JSON.stringify({passed:true,checks}));
    for(const win of [host,guest])await js(win,'session.ws?.close();');
    await server.close();app.exit(0);
  }catch(error){console.error(error);for(const win of [host,guest]){try{await js(win,'session.ws?.close();');}catch{}}await server.close();app.exit(1);}
}).catch(error=>{console.error(error);app.exit(1);});
